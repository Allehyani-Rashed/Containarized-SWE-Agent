from __future__ import annotations

import os
from pathlib import Path
from threading import RLock
from typing import Callable, Dict, Iterable, List, Optional
from urllib.parse import urlsplit

REPO_ROOT = Path(__file__).resolve().parents[2]


def _resolve_proxy_dir() -> Path:
    override = os.environ.get("PROXY_DIR")
    if override:
        candidate = Path(override).expanduser()
        if not candidate.is_absolute():
            candidate = (REPO_ROOT / candidate).resolve()
        return candidate
    return REPO_ROOT / "proxy"


PROXY_DIR = _resolve_proxy_dir()
BASE_ALLOWLIST_PATH = PROXY_DIR / "base_allowlist.conf"
GENERATED_FILTER_PATH = PROXY_DIR / "filter.list"
DEFAULT_BASE_ALLOWLIST = (
    "gitlab.com",
    "registry.npmjs.org",
    "pypi.org",
    "files.pythonhosted.org",
    "chatgpt.com"
)
DEFAULT_PROXY_URL = "http://codex-egress-proxy:8888"
DEFAULT_NO_PROXY = "localhost,127.0.0.1,.local"


LogFn = Optional[Callable[[str], None]]


_FILTER_LOCK = RLock()
_ACTIVE_ALLOWLISTS: Dict[int, List[str]] = {}
_CURRENT_FILTER_ENTRIES: List[str] = []


def normalize_host(raw: str) -> Optional[str]:
    """Normalize host/domain input, stripping scheme, paths, and whitespace."""

    if raw is None:
        return None
    candidate = raw.strip()
    if not candidate:
        return None

    wildcard_prefix = ""
    if candidate.startswith("*."):
        wildcard_prefix = "*."
        candidate = candidate[2:]
    elif candidate.startswith("."):
        wildcard_prefix = "."
        candidate = candidate[1:]

    parsed = urlsplit(candidate if "://" in candidate else f"//{candidate}", scheme="http")
    host = parsed.hostname or ""
    if not host:
        host = candidate.split("/")[0]
    host = host.strip().lower().rstrip(".")
    if not host:
        return None
    if wildcard_prefix:
        return f"{wildcard_prefix}{host}"
    return host


def _deduplicate(items: Iterable[str]) -> List[str]:
    seen: set[str] = set()
    result: list[str] = []
    for entry in items:
        if not entry:
            continue
        if entry not in seen:
            seen.add(entry)
            result.append(entry)
    return result


def _merge_active_allowlists_locked() -> List[str]:
    """Return the deduplicated union of the base allowlist and active task entries."""

    combined: list[str] = []
    combined.extend(load_base_allowlist())
    for entries in _ACTIVE_ALLOWLISTS.values():
        combined.extend(entries)
    return _deduplicate(combined)


def _update_filter_locked(entries: Iterable[str], log_fn: LogFn = None) -> Path:
    """Write Tinyproxy's filter only when the contents change."""

    global _CURRENT_FILTER_ENTRIES
    normalized = _deduplicate(entries)
    if normalized == _CURRENT_FILTER_ENTRIES:
        return GENERATED_FILTER_PATH
    path = write_filter_file(normalized)
    _CURRENT_FILTER_ENTRIES = normalized
    if log_fn:
        log_fn(f"Proxy filter updated at {path}")
    _reload_proxy(log_fn=log_fn)
    return path


def load_base_allowlist(project_host: Optional[str] = None) -> List[str]:
    """Return the merged base allowlist including the project GitLab host."""

    entries: list[str] = []
    if BASE_ALLOWLIST_PATH.exists():
        for raw in BASE_ALLOWLIST_PATH.read_text(encoding="utf-8").splitlines():
            if raw.strip().startswith("#"):
                continue
            normalized = normalize_host(raw)
            if normalized:
                entries.append(normalized)
    else:
        entries.extend(DEFAULT_BASE_ALLOWLIST)

    if project_host:
        normalized_host = normalize_host(project_host)
        if normalized_host:
            entries.append(normalized_host)

    return _deduplicate(entries)


def merge_allowlists(project_host: Optional[str], extras: Iterable[str]) -> List[str]:
    """Combine the base allowlist with per-task entries."""

    merged = load_base_allowlist(project_host)
    normalized_extras = [normalize_host(entry) for entry in extras]
    merged.extend(entry for entry in normalized_extras if entry)
    return _deduplicate(merged)


def write_filter_file(entries: Iterable[str]) -> Path:
    """Persist the merged allowlist into Tinyproxy's filter file."""

    PROXY_DIR.mkdir(parents=True, exist_ok=True)
    path = GENERATED_FILTER_PATH
    lines = ["# Autogenerated by Codex orchestrator", "# Do not edit manually"]
    for entry in entries:
        lines.append(entry)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _reload_proxy(log_fn: LogFn = None) -> bool:
    """Restart the Tinyproxy container so it re-reads the generated filter."""

    if os.environ.get("SKIP_PROXY_RELOAD") == "1":
        if log_fn:
            log_fn("Skipping proxy reload due to SKIP_PROXY_RELOAD=1")
        return False

    container_name = os.environ.get("PROXY_CONTAINER_NAME", "codex-egress-proxy")
    if not container_name:
        if log_fn:
            log_fn("Proxy container name missing; cannot trigger reload")
        return False

    try:
        import docker
        from docker.errors import APIError, DockerException, NotFound
    except ImportError:
        if log_fn:
            log_fn("docker SDK not available; skipping proxy reload")
        return False

    try:
        client = docker.from_env()
    except DockerException as exc:  # type: ignore[name-defined]
        if log_fn:
            log_fn(f"Unable to connect to Docker for proxy reload: {exc}")
        return False

    try:
        try:
            container = client.containers.get(container_name)
        except NotFound:  # type: ignore[name-defined]
            if log_fn:
                log_fn(f"Proxy container '{container_name}' not found; skipping reload")
            return False
        container.restart(timeout=10)
        if log_fn:
            log_fn("Tinyproxy container restarted to pick up new filter")
        return True
    except APIError as exc:  # type: ignore[name-defined]
        if log_fn:
            log_fn(f"Failed to signal proxy container: {exc}")
        return False
    finally:
        try:
            client.close()
        except Exception:
            pass


def refresh_proxy_allowlist(entries: Iterable[str], log_fn: LogFn = None) -> Path:
    """Write the filter file and attempt to reload the Tinyproxy container."""

    with _FILTER_LOCK:
        return _update_filter_locked(entries, log_fn=log_fn)


def apply_project_allowlist(
    task_id: int,
    project_host: Optional[str],
    extras: Iterable[str],
    *,
    log_fn: LogFn = None,
) -> List[str]:
    """Register a task's allowlist and refresh Tinyproxy with the aggregated union."""

    merged = merge_allowlists(project_host, extras)
    with _FILTER_LOCK:
        _ACTIVE_ALLOWLISTS[task_id] = merged
        combined = _merge_active_allowlists_locked()
        _update_filter_locked(combined, log_fn=log_fn)
    return merged


def clear_task_allowlist(task_id: int, *, log_fn: LogFn = None) -> List[str]:
    """Remove a task's allowlist contribution and refresh Tinyproxy."""

    with _FILTER_LOCK:
        _ACTIVE_ALLOWLISTS.pop(task_id, None)
        combined = _merge_active_allowlists_locked()
        _update_filter_locked(combined, log_fn=log_fn)
        return combined


def normalize_user_allowlist(entries: Iterable[str]) -> List[str]:
    """Normalize and deduplicate user-provided allowlist entries."""

    normalized = [normalize_host(entry) for entry in entries]
    return _deduplicate(entry for entry in normalized if entry)


def proxy_environment() -> dict[str, str]:
    """Return proxy-related environment variables for runner containers."""

    if os.environ.get("DISABLE_PROXY") == "1":
        return {}

    proxy_url = os.environ.get("PROXY_URL", DEFAULT_PROXY_URL)
    no_proxy = os.environ.get("NO_PROXY", DEFAULT_NO_PROXY)
    return {
        "HTTP_PROXY": proxy_url,
        "HTTPS_PROXY": proxy_url,
        "NO_PROXY": no_proxy,
    }
